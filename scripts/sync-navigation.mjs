import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const menu=JSON.parse(fs.readFileSync(path.join(root,'shared/navigation/v1/menu.json'),'utf8'));
const targets=[['shared/navigation/v1/nav.js','  const fallbackMenu = '+JSON.stringify(menu)+';'],['platform/packages/project-registry/src/navigation.generated.ts','export const sharedNavigationFallback = '+JSON.stringify(menu,null,2)+' as const;\n']];
for(let i=2;i<process.argv.length;i++){
 if(process.argv[i]==='--fallback'){const destination=process.argv[++i];if(!destination)throw Error('--fallback requires a generated TypeScript path');targets.push([destination,'export const sharedNavigationFallback = '+JSON.stringify(menu,null,2)+' as const;\n']);}
}
for(const [relative,generated] of targets){
 const destination=path.resolve(root,relative);
 const content=relative.endsWith('nav.js')?fs.readFileSync(destination,'utf8').replace(/(  \/\/ BEGIN GENERATED FALLBACK\n)[\s\S]*?(\n  \/\/ END GENERATED FALLBACK)/,(_whole,head,tail)=>head+generated+tail): '// Generated by scripts/sync-navigation.mjs from shared/navigation/v1/menu.json.\n'+generated;
 if(process.argv.includes('--check')){if(!fs.existsSync(destination)||fs.readFileSync(destination,'utf8')!==content)throw Error('Stale navigation fallback: '+relative);}
 else fs.writeFileSync(destination,content);
}
